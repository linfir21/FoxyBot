def shuffled_truth_deck() -> list[int]:
    "Перемешанные индексы фактов — в игре не повторяются, пока не пройдёшь все 5."
    deck = list(range(len(TRUTH_OR_LIE)))
    random.shuffle(deck)
    return deck

def reshuffled_truth_deck(previous: list[int]) -> list[int]:
    "Новая перетасовка: первый факт новой колоды не совпадает с последним старой."
    deck = shuffled_truth_deck()
    if previous and deck[0] == previous[-1]:
        deck[0], deck[-1] = deck[-1], deck[0]
    return deck

